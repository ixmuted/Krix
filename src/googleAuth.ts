export interface OwnerProfile {
  email: string;
  name?: string;
  picture?: string;
  expiresAt: number;
  role?: "owner" | "user";
}

export interface GeneratedKeyEntry {
  id: string;
  clientId: string;
  key: string;
  keyHash?: string;
  /** AES-256-GCM envelope for owner-initiated key reveal; never return in list APIs. */
  keyEncrypted?: string;
  prefix: string;
  label: string;
  email?: string;
  role?: "owner" | "user";
  createdAt: number;
  lastUsedAt?: number;
}

// In-memory registry of dynamic keys generated by the signed-in owner
const dynamicApiKeys = new Map<string, GeneratedKeyEntry>();
const revokedKeyIds = new Set<string>();

const KEYS_FILE = path.resolve(process.cwd(), "data", ".krix_keys.json");
const SECRET_FILE = path.resolve(process.cwd(), "data", ".krix_session_secret");

export function generateClientId(): string {
  const chars = "abcdefghijklmnopqrstuvwxyz0123456789";
  const bytes = crypto.randomBytes(12);
  let result = "";
  for (let i = 0; i < 12; i++) {
    result += chars[bytes[i] % chars.length];
  }
  return result;
}

let mongoDb: Db | null = null;
let mongoInitPromise: Promise<void> | null = null;

export function getMongoDb(): Db | null {
  return mongoDb;
}

export async function ensureMongoAuth(): Promise<void> {
  const uri =
    process.env.MONGODB_URI ||
    process.env.MONGO_URL ||
    process.env.DATABASE_URL;
  if (!uri) return;

  if (!mongoDb) {
    if (!mongoInitPromise) {
      mongoInitPromise = (async () => {
        try {
          const client = new MongoClient(uri, {
            serverSelectionTimeoutMS: 5000,
            connectTimeoutMS: 5000,
            appName: "krix-auth",
          });
          await client.connect();
          const dbName =
            process.env.MONGODB_DB_NAME || process.env.MONGODB_DB || "krix";
          mongoDb = client.db(dbName);
          await loadKeysFromMongo();
        } catch (err: any) {
          mongoDb = null;
          mongoInitPromise = null;
          console.error("[mongo-auth] connection or key-migration failure:", err?.message);
          throw err;
        }
      })();
    }
    await mongoInitPromise;
  } else {
    await loadKeysFromMongo();
  }
}
ensureMongoAuth().catch(() => {});

export async function loadKeysFromMongo(): Promise<void> {
  if (!mongoDb) return;
  try {
    const col = mongoDb.collection("api_keys");
    const docs = await col.find({}).toArray();
    for (const d of docs) {
      if (d.revoked) {
        if (d.id) revokedKeyIds.add(d.id);
        if (d.id) dynamicApiKeys.delete(d.id);
      } else if (d.id || d.key || d._id) {
        const id =
          d.id ||
          (d._id
            ? String(d._id)
            : `kx_${crypto.randomBytes(6).toString("hex")}`);
        const legacyRawKey = d.key || d.apiKey || "";
        const keyHash = d.keyHash || (legacyRawKey ? hashApiKey(legacyRawKey) : undefined);
        const encryptedLegacyKey = legacyRawKey ? encryptApiKey(legacyRawKey) : undefined;
        const entry: GeneratedKeyEntry = {
          id,
          clientId: d.clientId || generateClientId(),
          key: "", // API key secrets are never returned by list APIs.
          keyHash,
          keyEncrypted: d.keyEncrypted || encryptedLegacyKey,
          prefix: d.prefix || (legacyRawKey ? legacyRawKey.slice(0, 16) : id),
          label: d.label || d.name || "Personal Key",
          email: d.email,
          role: d.role,
          createdAt: d.createdAt || Date.now(),
          lastUsedAt: d.lastUsedAt,
        };
        dynamicApiKeys.set(id, entry);
        if (legacyRawKey) {
          registerSecret(legacyRawKey);
          // Remove a legacy plaintext value only after its encrypted replacement
          // has been generated. This avoids destructive migration in dev setups
          // that have not configured KEY_ENCRYPTION_SECRET yet.
          if (encryptedLegacyKey) {
            const legacyFilter = d.id ? { id: d.id } : { _id: d._id };
            await col.updateOne(legacyFilter, {
              $set: { keyHash, keyEncrypted: encryptedLegacyKey },
              $unset: { key: "", apiKey: "" },
            });
          }
        }
      }
    }
  } catch (err: any) {
    console.error("[mongo-auth] loadKeysFromMongo error:", err?.message);
    throw err;
  }
}

export async function syncKeyToMongo(entry: GeneratedKeyEntry): Promise<void> {
  await ensureMongoAuth();
  if (!mongoDb) {
    if (process.env.MONGODB_URI || process.env.MONGO_URL || process.env.DATABASE_URL) {
      throw new Error("MongoDB is configured but unavailable; API key persistence failed.");
    }
    return;
  }
  try {
    const col = mongoDb.collection("api_keys");
    const { key: _rawSecret, ...metadata } = entry;
    await col.updateOne(
      { id: entry.id },
      {
        $set: {
          ...metadata,
          keyHash: entry.keyHash || (_rawSecret ? hashApiKey(_rawSecret) : undefined),
          keyEncrypted: entry.keyEncrypted || (_rawSecret ? encryptApiKey(_rawSecret) : undefined),
          revoked: false,
          updatedAt: Date.now(),
        },
        $unset: { key: "", apiKey: "" },
      },
      { upsert: true },
    );
  } catch (err: any) {
    console.error("[mongo-auth] syncKeyToMongo error:", err?.message);
    throw err;
  }
}

export async function revokeKeyInMongo(id: string): Promise<void> {
  await ensureMongoAuth();
  if (!mongoDb) {
    if (process.env.MONGODB_URI || process.env.MONGO_URL || process.env.DATABASE_URL) {
      throw new Error("MongoDB is configured but unavailable; API key revocation cannot be confirmed.");
    }
    return;
  }
  try {
    const col = mongoDb.collection("api_keys");
    await col.updateOne(
      { id },
      { $set: { revoked: true, revokedAt: Date.now() } },
    );
  } catch (err: any) {
    console.error("[mongo-auth] revokeKeyInMongo error:", err?.message);
    throw err;
  }
}

function saveKeysToDisk(): void {
  try {
    fs.mkdirSync(path.dirname(KEYS_FILE), { recursive: true });
    const payload = {
      keys: Array.from(dynamicApiKeys.entries()).map(([id, entry]) => {
        const { key: _rawSecret, ...metadata } = entry;
        return [id, { ...metadata, keyHash: entry.keyHash || (_rawSecret ? hashApiKey(_rawSecret) : undefined), keyEncrypted: entry.keyEncrypted || (_rawSecret ? encryptApiKey(_rawSecret) : undefined), key: "" }];
      }),
      revoked: Array.from(revokedKeyIds),
    };
    fs.writeFileSync(KEYS_FILE, JSON.stringify(payload, null, 2), "utf-8");
  } catch {}
}

function loadKeysFromDisk(): boolean {
  let canRewrite = true;
  try {
    if (fs.existsSync(KEYS_FILE)) {
      const data = JSON.parse(fs.readFileSync(KEYS_FILE, "utf-8"));
      if (Array.isArray(data.keys)) {
        for (const [id, entry] of data.keys) {
          if (!entry.clientId) {
            entry.clientId = generateClientId();
          }
          const legacyRawKey = entry.key || "";
          const encryptedLegacyKey = legacyRawKey ? encryptApiKey(legacyRawKey) : undefined;
          entry.keyHash = entry.keyHash || (legacyRawKey ? hashApiKey(legacyRawKey) : undefined);
          entry.keyEncrypted = entry.keyEncrypted || encryptedLegacyKey;
          if (legacyRawKey && !encryptedLegacyKey && !entry.keyEncrypted) canRewrite = false;
          entry.key = "";
          dynamicApiKeys.set(id, entry);
          if (legacyRawKey) registerSecret(legacyRawKey);
        }
      }
      if (Array.isArray(data.revoked)) {
        for (const r of data.revoked) revokedKeyIds.add(r);
      }
    }
  } catch {
    return false;
  }
  return canRewrite;
}
const canRewriteLegacyKeyFile = loadKeysFromDisk();
// Rewrite local records only after legacy secret material has been encrypted.
if (canRewriteLegacyKeyFile) saveKeysToDisk();

function hashApiKey(value: string): string {
  return crypto.createHash("sha256").update(value).digest("hex");
}

function getSessionSecret(): string {
  if (process.env.SESSION_SECRET) return process.env.SESSION_SECRET;
  if (process.env.AUTH_SECRET) return process.env.AUTH_SECRET;
  if (process.env.MCP_API_KEY) return process.env.MCP_API_KEY;

  try {
    if (fs.existsSync(SECRET_FILE)) {
      const stored = fs.readFileSync(SECRET_FILE, "utf-8").trim();
      if (stored) return stored;
    }
    const gen = crypto.randomBytes(32).toString("hex");
    fs.mkdirSync(path.dirname(SECRET_FILE), { recursive: true });
    fs.writeFileSync(SECRET_FILE, gen, "utf-8");
    return gen;
  } catch (error) {
    // Never fall back to a known signing key. A predictable cookie secret
    // would let an attacker forge authenticated sessions.
    throw new Error(
      `Unable to load or persist the session signing secret: ${error instanceof Error ? error.message : String(error)}`,
    );
  }
}

function signCookiePayload(payload: string): string {
  const hmac = crypto.createHmac("sha256", getSessionSecret());
  hmac.update(payload);
  const sig = hmac.digest("base64url");
  return `${payload}.${sig}`;
}

function verifyCookiePayload(cookieValue: string): string | null {
  const parts = cookieValue.split(".");
  if (parts.length !== 2) return null;
  const [payload, sig] = parts;
  const hmac = crypto.createHmac("sha256", getSessionSecret());
  hmac.update(payload);
  const expectedSig = hmac.digest("base64url");
  if (!safeEqual(sig, expectedSig)) return null;
  return payload;
}

export function parseOwnerCookie(req: Request): OwnerProfile | null {
  const rawCookie = req.headers.cookie;
  if (!rawCookie) return null;
  const match = rawCookie.match(/(?:^|;\s*)krix_session=([^;]+)/);
  if (!match) return null;

  try {
    const rawVal = decodeURIComponent(match[1]);
    const payloadJson = verifyCookiePayload(rawVal);
    if (!payloadJson) return null;

    const data = JSON.parse(
      Buffer.from(payloadJson, "base64url").toString("utf-8"),
    ) as OwnerProfile;
    if (
      !data.email ||
      typeof data.expiresAt !== "number" ||
      Date.now() > data.expiresAt
    ) {
      return null;
    }

    if (!isAuthorizedEmail(data.email) && process.env.MULTI_USER === "false") {
      return null;
    }

    if (!data.role) {
      data.role = isOwnerEmail(data.email) ? "owner" : "user";
    }

    return data;
  } catch {
    return null;
  }
}

export function isAuthorizedEmail(email: string): boolean {
  const owner = (
    process.env.OWNER_EMAIL ||
    process.env.GOOGLE_ALLOWED_EMAIL ||
    ""
  )
    .trim()
    .toLowerCase();
  const allowed = (process.env.ALLOWED_EMAILS || "")
    .split(",")
    .map((e) => e.trim().toLowerCase())
    .filter(Boolean);

  const target = email.trim().toLowerCase();
  if (owner && target === owner) return true;
  if (allowed.includes(target)) return true;
  // If neither OWNER_EMAIL nor ALLOWED_EMAILS is configured, require explicit configuration
  return false;
}

export function findAuthorizedApiKey(
  candidateKey?: string | null,
): GeneratedKeyEntry | null {
  if (!candidateKey) return null;

  for (const entry of dynamicApiKeys.values()) {
    if (safeEqual(candidateKey, entry.key)) {
      entry.lastUsedAt = Date.now();
      return entry;
    }
  }

  // Stateless signed key verification: survives Render container restarts / redeploys!
  if (candidateKey.startsWith("krix_key_")) {
    const parts = candidateKey.slice("krix_key_".length).split(".");
    if (parts.length === 2) {
      const [b64, sig] = parts;
      const expected = crypto
        .createHmac("sha256", getSessionSecret())
        .update(b64)
        .digest("base64url");
      if (safeEqual(sig, expected)) {
        try {
          const payload = JSON.parse(
            Buffer.from(b64, "base64url").toString("utf-8"),
          );
          if (payload && payload.id && !revokedKeyIds.has(payload.id)) {
            const restoredEntry: GeneratedKeyEntry = {
              id: payload.id,
              clientId: payload.clientId || generateClientId(),
              key: candidateKey,
              prefix: candidateKey.slice(0, 16),
              label: payload.label || "Personal Key",
              email: payload.email,
              role: payload.role,
              createdAt: payload.iat || Date.now(),
              lastUsedAt: Date.now(),
            };
            dynamicApiKeys.set(restoredEntry.id, restoredEntry);
            registerSecret(candidateKey);
            return restoredEntry;
          }
        } catch {}
      }
    }
  }

  return null;
}

export function isAuthorizedApiKey(candidateKey?: string | null): boolean {
  if (!candidateKey) return false;
  const primaryKey = process.env.MCP_API_KEY;
  if (primaryKey && safeEqual(candidateKey, primaryKey)) {
    return true;
  }
  return findAuthorizedApiKey(candidateKey) !== null;
}

function apiKeyCipher(): Buffer {
  const secret = process.env.KEY_ENCRYPTION_SECRET || "";
  if (Buffer.byteLength(secret) < 32) {
    throw new Error("KEY_ENCRYPTION_SECRET must contain at least 32 bytes to enable API key reveal.");
  }
  return crypto.createHash("sha256").update(secret, "utf8").digest();
}

function encryptApiKey(secret: string): string | undefined {
  if (!process.env.KEY_ENCRYPTION_SECRET || Buffer.byteLength(process.env.KEY_ENCRYPTION_SECRET) < 32) return undefined;
  const iv = crypto.randomBytes(12);
  const cipher = crypto.createCipheriv("aes-256-gcm", apiKeyCipher(), iv);
  const ciphertext = Buffer.concat([cipher.update(secret, "utf8"), cipher.final()]);
  const tag = cipher.getAuthTag();
  return `v1.${iv.toString("base64url")}.${tag.toString("base64url")}.${ciphertext.toString("base64url")}`;
}

function decryptApiKey(envelope?: string): string | null {
  if (!envelope || !envelope.startsWith("v1.")) return null;
  try {
    const [, ivPart, tagPart, dataPart] = envelope.split(".");
    const decipher = crypto.createDecipheriv("aes-256-gcm", apiKeyCipher(), Buffer.from(ivPart, "base64url"));
    decipher.setAuthTag(Buffer.from(tagPart, "base64url"));
    return Buffer.concat([decipher.update(Buffer.from(dataPart, "base64url")), decipher.final()]).toString("utf8");
  } catch {
    return null;
  }
}

/** Reveal is deliberately limited to the account that created the key. */
export function getDynamicKeySecret(id: string, email: string): string | null {
  const entry = dynamicApiKeys.get(id);
  if (!entry || revokedKeyIds.has(id) || !entry.email || entry.email.toLowerCase() !== email.trim().toLowerCase()) return null;
  return decryptApiKey(entry.keyEncrypted);
}
export function createDynamicKey(
  label: string = "Personal Key",
  email?: string,
): GeneratedKeyEntry {
  if (dynamicApiKeys.size >= 30) {
    throw new Error(
      "Maximum limit of 30 API keys reached. Delete an unused key to create a new one.",
    );
  }

  const cleanLabel = (label || "").trim();
  if (cleanLabel.length < 4) {
    throw new Error("Key name must be at least 4 characters long.");
  }

  for (const existing of dynamicApiKeys.values()) {
    if (existing.label.toLowerCase() === cleanLabel.toLowerCase()) {
      throw new Error(
        `An API key named "${cleanLabel}" already exists. Please choose a unique name.`,
      );
    }
  }

  const id = `kx_${crypto.randomBytes(6).toString("hex")}`;
  const clientId = generateClientId();
  const effectiveEmail = email || getOwnerEmail() || "owner@localhost";
  const role: "owner" | "user" = isOwnerEmail(effectiveEmail)
    ? "owner"
    : "user";
  const payload = JSON.stringify({
    id,
    clientId,
    label: cleanLabel,
    email: effectiveEmail,
    role,
    iat: Date.now(),
  });
  const b64 = Buffer.from(payload).toString("base64url");
  const sig = crypto
    .createHmac("sha256", getSessionSecret())
    .update(b64)
    .digest("base64url");
  const raw = `krix_key_${b64}.${sig}`;
  registerSecret(raw);
  const entry: GeneratedKeyEntry = {
    id,
    clientId,
    key: raw,
    keyHash: hashApiKey(raw),
    keyEncrypted: encryptApiKey(raw),
    prefix: raw.slice(0, 16),
    label: cleanLabel,
    email: effectiveEmail,
    role,
    createdAt: Date.now(),
  };
  dynamicApiKeys.set(id, entry);
  saveKeysToDisk();
  syncKeyToMongo(entry).catch(() => {});
  // Persist the account association and a distinct sandbox ID for this key.
  const settings = getKeySettings(id);
  settings.email = effectiveEmail.trim().toLowerCase();
  settings.role = role;
  settings.sandboxId = generateSandboxId(id, role === "owner");
  settings.updatedAt = Date.now();
  updateKeyCredentials(id, effectiveEmail);
  return entry;
}

export function listDynamicKeys(userEmail?: string): GeneratedKeyEntry[] {
  const isOwner = isOwnerEmail(userEmail);
  const seenKeys = new Set<string>();
  const seenIds = new Set<string>();
  const result: GeneratedKeyEntry[] = [];

  for (const entry of dynamicApiKeys.values()) {
    if (revokedKeyIds.has(entry.id)) continue;
    if (
      userEmail &&
      (!entry.email || entry.email.trim().toLowerCase() !== userEmail.trim().toLowerCase())
    ) {
      continue;
    }
    if (entry.id && seenIds.has(entry.id)) continue;
    if (entry.key && seenKeys.has(entry.key)) continue;

    if (entry.id) seenIds.add(entry.id);
    if (entry.key) seenKeys.add(entry.key);
    result.push(entry);
  }
  return result;
}

export function revokeDynamicKey(id: string): boolean {
  revokedKeyIds.add(id);
  const deleted = dynamicApiKeys.delete(id);
  saveKeysToDisk();
  revokeKeyInMongo(id).catch(() => {});
  return deleted;
}

export function renameDynamicKey(
  id: string,
  newLabel: string,
): GeneratedKeyEntry {
  const cleanLabel = (newLabel || "").trim();
  if (cleanLabel.length < 4) {
    throw new Error("Key name must be at least 4 characters long.");
  }

  const entry = dynamicApiKeys.get(id);
  if (!entry) {
    throw new Error("API key not found.");
  }

  for (const existing of dynamicApiKeys.values()) {
    if (
      existing.id !== id &&
      existing.label.toLowerCase() === cleanLabel.toLowerCase()
    ) {
      throw new Error(
        `An API key named "${cleanLabel}" already exists. Please choose a unique name.`,
      );
    }
  }

  entry.label = cleanLabel;
  saveKeysToDisk();
  syncKeyToMongo(entry).catch(() => {});
  return entry;
}

export function getPublicBaseUrl(req: Request): string {
  if (process.env.PUBLIC_BASE_URL) {
    return process.env.PUBLIC_BASE_URL.replace(/\/+$/, "");
  }
  const protoRaw = (req.headers["x-forwarded-proto"] as string)
    ?.split(",")[0]
    .trim()
    .toLowerCase();
  const proto =
    protoRaw === "http" || protoRaw === "https"
      ? protoRaw
      : req.protocol === "http"
        ? "http"
        : "https";
  const host = req.get("host") || "localhost:3000";
  return `${proto}://${host}`;
}

export function requireOwnerAuth(
  req: Request,
  res: Response,
  next: NextFunction,
): void {
  const owner = parseOwnerCookie(req);
  if (!owner) {
    if (req.xhr || req.headers.accept?.includes("application/json")) {
      res.status(401).json({
        error: "Authentication required. Please sign in with Google.",
      });
      return;
    }
    const returnTo = encodeURIComponent(req.originalUrl || "/");
    res.redirect(`/auth/google?returnTo=${returnTo}`);
    return;
  }
  (req as any).owner = owner;
  next();
}

